import { describe, expect, test } from "vitest";
import {
  EDGE_UNAVAILABLE_BODY,
  EDGE_UNAVAILABLE_HTML,
  EDGE_UNAVAILABLE_SENTINEL,
} from "./edge-unavailable";
import { stripComments, extractBlocks } from "../system/proxy/import/parse-utils";

/**
 * The page is embedded in an nginx `return 503 '<body>'` inside the retained
 * vhost's `location /`, so the config tokenizer is part of its contract. These are
 * not style checks: each one of them, violated, produces a config that fails
 * `openresty -t` — which means a crash-looping fresh edge, or an existing edge that
 * refuses this and every LATER reload, freezing route changes for every site on
 * the box.
 *
 * The reasons are the same ones `edge-not-found.test.ts` and
 * `edge-upstream-down.test.ts` document at length; this file repeats the
 * assertions rather than the essays, because the three pages are written and
 * edited independently and a shared helper would let one drift.
 */
describe("edge unavailable page", () => {
  test("contains no single quote — it would end the nginx token mid-page", () => {
    expect(EDGE_UNAVAILABLE_HTML).not.toContain("'");
  });

  test("contains no $ — nginx interpolates variables in a return body", () => {
    expect(EDGE_UNAVAILABLE_HTML).not.toContain("$");
  });

  test("is a single line — both writers must serve identical bytes", () => {
    expect(EDGE_UNAVAILABLE_HTML).not.toContain("\n");
  });

  test("contains no # — Openship's OWN config reader cuts lines at one", () => {
    // Use rgb() for colours. A CSS hex triplet here truncates the line mid-page in
    // `stripComments`, taking its closing braces with it and breaking the brace balance
    // for every vhost the reader sees after it.
    expect(EDGE_UNAVAILABLE_HTML).not.toContain("#");
  });

  test("keeps its braces balanced — the same reader counts them", () => {
    const open = (EDGE_UNAVAILABLE_HTML.match(/\{/g) ?? []).length;
    const close = (EDGE_UNAVAILABLE_HTML.match(/\}/g) ?? []).length;
    expect(open).toBe(close);
  });

  test("survives a round trip through the reader that parses these files back", () => {
    // The end-to-end version of the two above, against a vhost shaped like the one
    // the generator emits for a retained unavailable route: the page sits inside
    // `location /`, so a brace or comment character escaping it would swallow the
    // rest of the block and the box would scan as fewer sites than it serves.
    const conf = `# Auto-generated by Openship - do not edit manually
server {
    listen 80;
    server_name app.example.com;

    location / {
        ${EDGE_UNAVAILABLE_BODY}
    }
}

server {
    listen 443 ssl;
    server_name app.example.com;

    location / {
        ${EDGE_UNAVAILABLE_BODY}
    }
}
`;
    expect(extractBlocks(stripComments(conf), "server")).toHaveLength(2);
  });

  test("carries the sentinel in the first 200 bytes", () => {
    // So `curl -s https://host | head -c 200` says "our edge, retained host,
    // backend withdrawn" rather than leaving an operator to guess whose 503 they
    // are looking at.
    expect(EDGE_UNAVAILABLE_HTML.indexOf(EDGE_UNAVAILABLE_SENTINEL)).toBeGreaterThan(-1);
    expect(EDGE_UNAVAILABLE_HTML.indexOf(EDGE_UNAVAILABLE_SENTINEL)).toBeLessThan(200);
  });

  test("is a marker NO other error page uses", () => {
    // The three pages are told apart at a glance by `curl | head -c 200`; a
    // collision would make "nothing is deployed" and "deployed, stopped" read
    // alike.
    expect(EDGE_UNAVAILABLE_SENTINEL).not.toBe("openship-edge-unrouted");
    expect(EDGE_UNAVAILABLE_SENTINEL).not.toBe("openship-edge-upstream-down");
  });

  test("makes no external request and carries no link at all", () => {
    // The upstream-down page's rule: the report it fixes is a THIRD PARTY's link
    // on an operator's error page, so the absence of links is the fix, not a
    // detail. It is also served to strangers, so a third-party fetch would leak
    // their visit and a dashboard URL would advertise infrastructure.
    expect(EDGE_UNAVAILABLE_HTML).not.toMatch(/https?:\/\//);
    expect(EDGE_UNAVAILABLE_HTML).not.toContain("<a ");
    expect(EDGE_UNAVAILABLE_HTML).not.toContain("<script");
  });

  test("never reflects the requested hostname", () => {
    // `$host` is attacker-chosen and nginx's host validation permits `<`, `>` and `"`.
    expect(EDGE_UNAVAILABLE_BODY).not.toContain("$host");
  });

  test("leaks no internal facts — no ports, no upstream URLs, no error text", () => {
    // The retained vhost's route carries an IP + port upstream and the container
    // name behind it; the visitor page is a CONSTANT so nothing route-specific
    // can reach it, and the assertions keep it that way against well-meant
    // "helpful" edits (a port here is recon for anyone who can reach the box).
    // digit-colon-digit, not just any colon: the CSS is full of `name:value`.
    expect(EDGE_UNAVAILABLE_HTML).not.toMatch(/\d:\d/);
    expect(EDGE_UNAVAILABLE_HTML).not.toContain("proxy_pass");
    expect(EDGE_UNAVAILABLE_HTML).not.toContain("container");
  });

  test("answers text/html regardless of the URI's extension", () => {
    // `return` with a body types the response from the request URI, so a stopped
    // app's `/app.css` would be `Content-Type: text/css` with an HTML body.
    // Clearing the map is what makes `default_type` apply.
    const typesAt = EDGE_UNAVAILABLE_BODY.indexOf("types { }");
    const defaultAt = EDGE_UNAVAILABLE_BODY.indexOf("default_type text/html;");
    expect(typesAt).toBeGreaterThan(-1);
    expect(defaultAt).toBeGreaterThan(typesAt);
  });

  test("returns 503 — the retained vhost's status is the failure, stated plainly", () => {
    expect(EDGE_UNAVAILABLE_BODY).toContain("return 503 '");
  });

  test("carries no add_header — headers live at server scope", () => {
    // The inheritance invariant on `renderServerHeaders`: nginx replaces the whole
    // inherited set when a location declares an add_header of its own. The
    // `Cache-Control: no-store` this page needs is emitted at server scope in
    // nginx.ts; a location-level one here would break that invariant the day this
    // route shape gained header rules.
    expect(EDGE_UNAVAILABLE_BODY).not.toContain("add_header");
  });

  test("does not set server_tokens — that would be a vhost-wide side effect", () => {
    // The 404 page carries it scoped to the catch-alls on purpose. This body is
    // emitted into the retained vhost's serving location; a `server_tokens` here
    // would change the `Server:` header for the whole vhost as a side effect of
    // an error page.
    expect(EDGE_UNAVAILABLE_BODY).not.toContain("server_tokens");
  });

  test("says what happened, that it is temporary, and what to do", () => {
    // The one thing the page exists to communicate — and the distinction the stock
    // OpenResty 503 destroys, shared with the 404 ("nothing is deployed here") and
    // upstream-down ("deployed and not answering") pages: this one is "deployed,
    // stopped, coming back". One heading and one line of guidance — no bullet
    // list, no claims about the backend's internals.
    expect(EDGE_UNAVAILABLE_HTML).toContain("Application temporarily unavailable");
    expect(EDGE_UNAVAILABLE_HTML).toContain("Please try again in a moment.");
    // A transient state must never be the version of the host that enters an index.
    expect(EDGE_UNAVAILABLE_HTML).toContain("noindex");
  });

  test("carries no visible product branding", () => {
    // The page answers on the OPERATOR's domain for the operator's visitors — a
    // vendor footer there advertises a third party on someone else's site. The
    // sentinel comment stays the ONLY product identifier (invisible, for
    // `curl | head -c 200`), so strip HTML comments before looking for the name.
    expect(EDGE_UNAVAILABLE_HTML).not.toContain("Served by");
    expect(EDGE_UNAVAILABLE_HTML.replace(/<!--[\s\S]*?-->/g, "")).not.toMatch(/openship/i);
    expect(EDGE_UNAVAILABLE_HTML).not.toContain("<footer");
  });

  test("makes no request beyond the document itself — inline styles and SVG only", () => {
    // No image fetch, no stylesheet import, no font: a visitor's browser must not
    // contact anything but the edge that served the page (which may be the box's
    // ONLY working listener).
    expect(EDGE_UNAVAILABLE_HTML).not.toContain("<img");
    expect(EDGE_UNAVAILABLE_HTML).not.toContain("<link");
    expect(EDGE_UNAVAILABLE_HTML).not.toMatch(/url\(/i);
    expect(EDGE_UNAVAILABLE_HTML).not.toContain("@import");
    expect(EDGE_UNAVAILABLE_HTML).toContain("<svg");
  });

  test("supports light and dark appearances", () => {
    expect(EDGE_UNAVAILABLE_HTML).toContain("color-scheme:light dark");
    expect(EDGE_UNAVAILABLE_HTML).toContain("prefers-color-scheme:dark");
  });

  test("names no status code in the body", () => {
    // The status line carries the real code. A "503" printed in the tag would be
    // redundant with the one thing nginx already says truthfully.
    expect(EDGE_UNAVAILABLE_HTML).not.toContain("503");
  });

  test("does not promise a restart that routing does not perform", () => {
    // "Please try again in a moment." is guidance for the VISITOR, not a promise
    // about the backend: the page must not claim the app stopped, restarts, or
    // returns on any schedule — resumption is the reconciler's job on the
    // backend's own lifecycle, not the page's.
    expect(EDGE_UNAVAILABLE_HTML).not.toContain("will return automatically");
    expect(EDGE_UNAVAILABLE_HTML).not.toContain("has stopped");
    expect(EDGE_UNAVAILABLE_HTML).not.toContain("when the application starts");
  });
});
